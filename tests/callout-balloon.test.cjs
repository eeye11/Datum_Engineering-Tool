test('interior rectangle and circle attachments follow resize and rotation',()=>{
 const {calloutReferenceAt,resolveCalloutReference}=require(locate('callout-reference.js'));
 const rect=model.geometryFactories.rectangle({x:200,y:100},80,40);
 const local={objects:[rect],camera:{zoom:1}};
 const ref=calloutReferenceAt({x:220,y:85},local);
 assert.equal(ref.kind,'rectangle-point');
 rect.geometry.width=160;rect.geometry.height=80;
 assert.deepEqual(resolveCalloutReference(ref,local),{x:240,y:70});
 rect.geometry.rotation=90;
 const rotated=resolveCalloutReference(ref,local);assert.ok(Math.abs(rotated.x-270)<1e-7);assert.ok(Math.abs(rotated.y-20)<1e-7);
 const circle=model.geometryFactories.circle({x:-200,y:-100},20);local.objects=[circle];
 const circular=calloutReferenceAt({x:-200+20/Math.sqrt(2),y:-100+20/Math.sqrt(2)},local);
 assert.equal(circular.kind,'circle-point');circle.geometry.radius=40;
 const moved=resolveCalloutReference(circular,local);
 assert.ok(Math.abs(moved.x-(-200+40/Math.sqrt(2)))<1e-7);
});
