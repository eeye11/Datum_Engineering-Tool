test('dragging the balloon moves only the box; dragging the arrow tip reattaches it',()=>{
 const drag=require(locate('drag.js'));
 model.setActiveTool(state,'select');model.selectObject(state,marker.id);
 const start={...live().geometry.end},attachment={...live().geometry.start};
 assert.equal(drag.beginManipulationDrag(event(start)),true);
 drag.updateManipulationDrag(event({x:start.x-15,y:start.y+10}));
 drag.finishManipulationDrag(event({x:start.x-15,y:start.y+10}));
 assert.deepEqual(live().geometry.start,attachment);
 assert.ok(Math.abs(live().geometry.end.x-(start.x-15))<1e-7);
 assert.deepEqual(live().geometry.position,live().geometry.end);
 const target=model.addObject(state,model.geometryFactories.line({x:-80,y:0},{x:-80,y:40}));
 const tip={...live().geometry.start};
 assert.equal(drag.beginManipulationDrag(event(tip)),true);
 drag.updateManipulationDrag(event({x:-80,y:20}));drag.finishManipulationDrag(event({x:-80,y:20}));
 assert.equal(live().anchorRef.featureId,target.id);assert.equal(live().targetFeatureId,target.id);
 assert.deepEqual(live().geometry.start,{x:-80,y:20});
});
