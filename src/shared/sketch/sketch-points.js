/*
 * ============================================================
 * THE SHARED SKETCH POINT MODEL
 * ============================================================
 *
 * Every sketch-based tool in DAETUM works with the same kinds of point, and this
 * module is where that is defined ONCE. A tool that grew its own point system
 * would be a second definition of "anchor", free to disagree with the first -
 * and the meaning of an anchor must not depend on which editor the student
 * happens to have open.
 *
 * THE KINDS, AND WHY THEY ARE NOT THE SAME THING
 * ----------------------------------------------
 *
 *   anchor    EXACT. A geometric constraint the student placed. Corrected
 *             geometry must pass through it, and no fitting algorithm may move
 *             it because another curve would have been easier to build.
 *
 *   control   A Bezier handle. It controls curvature and generally does NOT lie
 *             on the curve. It is NOT a constraint - moving it changes the curve
 *             once, and a refit is free to replace it.
 *
 *   inferred  Generated by recognition and fitting - a vertex, an arc midpoint,
 *             a fitted centre. The student did not put it there and cannot
 *             select it; it is reported so a test and the inspector can see
 *             what the solver decided.
 *
 * THERE IS NO "SHAPE GUIDE".
 *
 * A guide was a soft constraint: a point the curve was pulled toward but not
 * required to pass through. It was removed because the student's own STROKE is
 * already the soft constraint - it says exactly where the shape should go, in
 * far more detail than a handful of guide points ever could - and asking for
 * guides as well made the student describe their drawing twice. The stroke is
 * the fitting reference; an anchor is the only thing that overrides it.
 *
 * Keeping the remaining kinds in one model, with one `type` field and one set of
 * semantics, is what lets the canvas, the inspector, the corrector and every
 * geometry adapter ask the same question and get the same answer.
 *
 * COORDINATES: THREE WAYS TO SAY THE SAME THING
 * ---------------------------------------------
 *
 * A point's AUTHORITATIVE value is the absolute (x, y) in sketch model space.
 * Relative and polar are DEFINITIONS of that value, not a second copy of it:
 *
 *   absolute   x, y direct
 *   relative   P = P_ref + (dx, dy)
 *   polar      P = P_ref + (r cos t, r sin t)
 *
 * The definition is what a student edits; the absolute value is what every
 * consumer reads. `resolvePoint` is the ONE place a definition becomes an
 * absolute coordinate, so the canvas, the table and the source cannot disagree.
 *
 * SCREEN PIXELS ARE NOT STORED HERE. Not once, not as a convenience. Converting
 * a pointer position into model space happens at the interaction boundary (see
 * `sketch-viewport.js`) and nowhere else.
 */

/* The point kinds, in the order the interface lists them. */
export const SKETCH_POINT_TYPES = Object.freeze([
  "anchor",
  "control",
  "inferred",
]);

/*
 * THE ONE KIND A STUDENT CREATES AND EDITS.
 *
 * An ANCHOR is a point the corrected geometry must pass through. There is no
 * second kind: a "shape guide" was a soft constraint, and the student's own
 * STROKE is already the soft constraint - it says where the shape goes in far
 * more detail than a handful of points could. Control handles and inferred
 * vertices are the GEOMETRY's, and are not the student's to place.
 */
export const USER_POINT_TYPES = Object.freeze(["anchor"]);

/* How a point's coordinates are stated. */
export const COORDINATE_MODES = Object.freeze([
  "absolute",
  "relative",
  "polar",
]);

/* Degrees are what a student types; radians are what the arithmetic uses. */
export const DEG_PER_RAD = 180 / Math.PI;

const EPSILON = 1e-9;

let nextPointSerial = 1;

/* A fresh id. Stable within a session and unique across every editor. */
export function nextPointId(prefix = "pt") {
  const id = `${prefix}-${nextPointSerial}`;
  nextPointSerial += 1;

  return id;
}

/* For tests that must start from a known counter. */
export function resetPointIds(start = 1) {
  nextPointSerial = start;
}

function finite(value, fallback = 0) {
  const number = Number(value);

  return Number.isFinite(number) ? number : fallback;
}

function copyPoint(point) {
  return { x: Number(point.x) || 0, y: Number(point.y) || 0 };
}

/* A point at the origin, of the given kind - the shape every created point has. */
export function makePoint({
  id = null,
  name = "",
  type = "anchor",
  x = 0,
  y = 0,
  coordinateMode = "absolute",
  referenceId = null,
  delta = null,
  distance = null,
  angleDeg = null,
  locked = false,
  visible = true,
  geometryId = null,
  parameter = null,
} = {}) {
  if (!SKETCH_POINT_TYPES.includes(type)) {
    throw new Error(`Unknown sketch point type: ${type}`);
  }

  if (!COORDINATE_MODES.includes(coordinateMode)) {
    throw new Error(`Unknown coordinate mode: ${coordinateMode}`);
  }

  return {
    id: id || nextPointId(type === "anchor" ? "a" : "p"),
    name,
    type,
    x: finite(x),
    y: finite(y),
    coordinateMode,
    referenceId,
    delta: delta ? { dx: finite(delta.dx), dy: finite(delta.dy) } : null,
    distance: distance === null ? null : finite(distance),
    angleDeg: angleDeg === null ? null : finite(angleDeg),
    /*
     * LOCKING IS NOT A SEPARATE CONSTRAINT TYPE. A locked point is one whose
     * coordinates the interface will not let a drag or a fit change - it keeps
     * its own case, and every writer of coordinates honours this one flag.
     */
    locked: Boolean(locked),
    visible: visible !== false,
    /*
     * WHICH GEOMETRY THE POINT BELONGS TO, when it was placed ON one. Null
     * means the point stands on its own - an anchor the student dropped in
     * space to draw against.
     */
    geometryId,
    /* Where on that geometry, in the geometry's own parameterisation. */
    parameter: parameter === null ? null : finite(parameter),
  };
}

/* ============================================================
 * RESOLVING A DEFINITION TO AN ABSOLUTE COORDINATE
 * ============================================================ */

/*
 * The ONE conversion from a point's stated definition to its absolute value.
 *
 * `byId` is the points map (or array) a reference is looked up in. A reference
 * that is missing or is the point itself is not an error the interface should
 * throw over - it is a half-built state, and the point keeps its stored
 * absolute value until the reference exists. Every reader goes through here so
 * a relative point can never be read as two different coordinates by two
 * panels.
 */
export function resolvePoint(point, byId = null) {
  if (!point) {
    return null;
  }

  const mode = COORDINATE_MODES.includes(point.coordinateMode)
    ? point.coordinateMode
    : "absolute";

  if (mode === "absolute") {
    return copyPoint(point);
  }

  const reference = lookup(byId, point.referenceId);

  if (!reference || reference.id === point.id) {
    return copyPoint(point);
  }

  const base = resolvePoint(reference, byId);

  if (!base) {
    return copyPoint(point);
  }

  if (mode === "relative") {
    const delta = point.delta || { dx: 0, dy: 0 };

    return {
      x: base.x + finite(delta.dx),
      y: base.y + finite(delta.dy),
    };
  }

  /* polar */
  const radius = Math.max(0, finite(point.distance));
  const theta = (finite(point.angleDeg) * Math.PI) / 180;

  return {
    x: base.x + radius * Math.cos(theta),
    y: base.y + radius * Math.sin(theta),
  };
}

function lookup(byId, id) {
  if (!byId || !id) {
    return null;
  }

  if (Array.isArray(byId)) {
    return byId.find((entry) => entry && entry.id === id) || null;
  }

  return byId[id] || null;
}

/*
 * Resolve a whole list, in dependency order.
 *
 * A relative point may reference another relative point, so the list is walked
 * until it stops changing - with a step cap, because a reference CYCLE (A
 * relative to B, B relative to A) is a real mistake a student can make and it
 * must settle on something rather than spin.
 */
export function resolvePoints(points = []) {
  const list = Array.isArray(points) ? points.filter(Boolean) : [];
  const byId = new Map(list.map((point) => [point.id, point]));

  const resolved = new Map();

  const resolveOne = (point, seen = new Set()) => {
    if (resolved.has(point.id)) {
      return resolved.get(point.id);
    }

    if (seen.has(point.id)) {
      /* A cycle: the point keeps what it has, and we say so by stopping. */
      return copyPoint(point);
    }

    seen.add(point.id);

    if (point.coordinateMode === "absolute" || !point.referenceId) {
      const value = copyPoint(point);
      resolved.set(point.id, value);

      return value;
    }

    const reference = byId.get(point.referenceId);

    if (!reference || reference.id === point.id) {
      const value = copyPoint(point);
      resolved.set(point.id, value);

      return value;
    }

    const base = resolveOne(reference, seen);

    const value =
      point.coordinateMode === "relative"
        ? {
            x: base.x + finite(point.delta?.dx),
            y: base.y + finite(point.delta?.dy),
          }
        : {
            x:
              base.x +
              Math.max(0, finite(point.distance)) *
                Math.cos((finite(point.angleDeg) * Math.PI) / 180),
            y:
              base.y +
              Math.max(0, finite(point.distance)) *
                Math.sin((finite(point.angleDeg) * Math.PI) / 180),
          };

    resolved.set(point.id, value);

    return value;
  };

  list.forEach((point) => resolveOne(point));

  return list.map((point) => ({
    ...point,
    absolute: copyPoint(resolved.get(point.id) || point),
  }));
}

/* ============================================================
 * CHANGING A DEFINITION
 * ============================================================ */

/*
 * Restate a point in a coordinate mode, keeping it exactly where it is.
 *
 * Switching a point from absolute to relative to an existing point should not
 * MOVE it - the student changed how they describe it, not where it is. So the
 * definition is derived from the current absolute position and the reference.
 */
export function withCoordinateMode(point, mode, reference = null, byId = null) {
  if (!COORDINATE_MODES.includes(mode)) {
    return point;
  }

  const here = resolvePoint(point, byId);

  if (mode === "absolute" || !reference) {
    return {
      ...point,
      coordinateMode: "absolute",
      referenceId: null,
      delta: null,
      distance: null,
      angleDeg: null,
      x: here.x,
      y: here.y,
    };
  }

  const base = resolvePoint(reference, byId);
  const dx = here.x - base.x;
  const dy = here.y - base.y;

  if (mode === "relative") {
    return {
      ...point,
      coordinateMode: "relative",
      referenceId: reference.id,
      delta: { dx, dy },
      distance: null,
      angleDeg: null,
      x: here.x,
      y: here.y,
    };
  }

  return {
    ...point,
    coordinateMode: "polar",
    referenceId: reference.id,
    delta: null,
    distance: Math.hypot(dx, dy),
    angleDeg: Math.atan2(dy, dx) * DEG_PER_RAD,
    x: here.x,
    y: here.y,
  };
}

/*
 * Set a point's absolute position, honouring its definition.
 *
 * An ABSOLUTE point takes the value directly. A RELATIVE or POLAR point takes
 * it as the new offset from its reference - which is what dragging a dependent
 * point means, and what keeps the reference relationship intact.
 */
export function withAbsolutePosition(point, x, y, byId = null) {
  const base =
    point.coordinateMode === "absolute" || !point.referenceId
      ? null
      : lookup(byId, point.referenceId);

  const reference = base ? resolvePoint(base, byId) : null;

  if (!reference) {
    return { ...point, x: finite(x), y: finite(y) };
  }

  const dx = finite(x) - reference.x;
  const dy = finite(y) - reference.y;

  if (point.coordinateMode === "relative") {
    return { ...point, x: finite(x), y: finite(y), delta: { dx, dy } };
  }

  return {
    ...point,
    x: finite(x),
    y: finite(y),
    distance: Math.hypot(dx, dy),
    angleDeg: Math.atan2(dy, dx) * DEG_PER_RAD,
  };
}



/* ============================================================
 * SELECTION AND CLASSIFICATION
 * ============================================================ */

/* The points a corrector must treat as exact, in list order. */
export function anchorPoints(points = []) {
  return resolvePoints(points).filter((point) => point.type === "anchor");
}



/*
 * Whether a point is a constraint at all.
 *
 * Control handles and inferred vertices are part of the GEOMETRY, not part of
 * the student's constraint set. A corrector asking "what must I honour?" gets
 * this answer, never a handle.
 */
export function isConstraint(point) {
  return Boolean(point) && USER_POINT_TYPES.includes(point.type);
}

/* Whether a point's coordinates may be changed by a drag or a fit. */
export function isMovable(point) {
  return Boolean(point) && !point.locked;
}

/* ============================================================
 * POINT INSERTION ON EXISTING GEOMETRY
 * ============================================================
 *
 * The student must be able to click ANYWHERE on a curve and put a point there -
 * not only at the ends, and not only at the samples a freehand stroke happened
 * to produce. So the interface asks a geometry adapter for the CLOSEST POINT ON
 * ITS ACTUAL MATHEMATICS, and this module turns that answer into a point.
 *
 * The adapter contract (see `sketch-geometry-adapters.js`):
 *
 *     project(point)  ->  { x, y, t, distance }
 *
 * `t` is the adapter's own parameter along the geometry - 0..1 for a curve or a
 * segment, an angle for a circle. This module never interprets it further: the
 * adapter that produced it is the adapter that will use it.
 */

/* The nearest point on `geometry` to `target`, as an anchor. */
export function insertPointOnGeometry({
  geometry,
  target,
  type = "anchor",
  name = "",
  id = null,
  project = null,
} = {}) {
  if (!geometry) {
    return null;
  }

  const projected = typeof project === "function" ? project(target) : null;

  if (
    !projected ||
    !Number.isFinite(projected.x) ||
    !Number.isFinite(projected.y)
  ) {
    return null;
  }

  return makePoint({
    id,
    name,
    type,
    x: projected.x,
    y: projected.y,
    geometryId: geometry.id || null,
    parameter: Number.isFinite(projected.t) ? projected.t : null,
  });
}

/* ============================================================
 * NAMING
 * ============================================================ */

/*
 * Sequential names a student can talk about: P1, P2, P3.
 *
 * The number is the smallest one not already taken, so deleting P2 and adding
 * a point gives P2 again rather than P5 - a list that only ever grows its
 * numbers reads as though points were lost.
 */
export function nextPointName(points = [], prefix = "P") {
  const taken = new Set(
    (Array.isArray(points) ? points : [])
      .map((point) => String(point?.name || ""))
      .filter((name) => name.startsWith(prefix)),
  );

  let index = 1;

  while (taken.has(`${prefix}${index}`)) {
    index += 1;
  }

  return `${prefix}${index}`;
}

/* ============================================================
 * CONVERSIONS FOR DISPLAY
 * ============================================================ */

/* A number with no trailing zeros, for a readout. */
export function numberText(value, decimals = 2) {
  const number = Number(value);

  if (!Number.isFinite(number)) {
    return "-";
  }

  const rounded = Number(number.toFixed(decimals));

  return String(Object.is(rounded, -0) ? 0 : rounded);
}

/* The offset a relative definition currently describes. */
export function relativeOffset(point, byId = null) {
  const here = resolvePoint(point, byId);

  if (!point.referenceId) {
    return { dx: 0, dy: 0 };
  }

  const base = resolvePoint(lookup(byId, point.referenceId), byId);

  if (!base) {
    return { dx: 0, dy: 0 };
  }

  return { dx: here.x - base.x, dy: here.y - base.y };
}

/* The radius and angle a polar definition currently describes. */
export function polarFrom(point, byId = null) {
  const { dx, dy } = relativeOffset(point, byId);

  return {
    r: Math.hypot(dx, dy),
    angleDeg: Math.atan2(dy, dx) * DEG_PER_RAD,
  };
}

/*
 * Whether a point definition is complete.
 *
 * An interface needs to know this to decide whether to draw a point at all and
 * whether to show it as "dependent" - and a relative point whose reference was
 * deleted is incomplete until the student picks another.
 */
export function isDefinitionComplete(point) {
  if (!point) {
    return false;
  }

  if (point.coordinateMode === "absolute") {
    return Number.isFinite(Number(point.x)) && Number.isFinite(Number(point.y));
  }

  return Boolean(point.referenceId);
}

