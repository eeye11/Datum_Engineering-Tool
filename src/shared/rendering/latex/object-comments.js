/* The readable name a header states for an object of `type`. */
export function objectTypeLabel(type) {
  const key = clean(type);
  const fallback = key.replace(/[-_]+/g, " ").replace(/\b\w/g, (letter) => letter.toUpperCase());

  return TYPE_LABELS[key] || fallback || "Object";
}

/*
 * What the header calls this object.
 *
 * A feature's `name` is the one the Objects list shows, so it is the most
 * useful name for a student reading the source. It is only ever used HERE, in
 * a comment - never as drawing text (see the label rules in the writers).
 */
export function objectDisplayName(object, { type = null, label = null } = {}) {
  const name = clean(object?.name);

  if (name) {
    return name;
  }

  if (label) {
    return `${objectTypeLabel(type || object?.type)} ${clean(label)}`;
  }

  return objectTypeLabel(type || object?.type);
}

/* ============================================================
 * STABLE IDS
 * ============================================================
 *
 * The model already mints an id when the object is created
 * (`drawing-state.js`), and that id is what the source block is keyed on. This
 * only guarantees one exists - a test fixture or an imported object without an
 * id gets a stable one on its first write, and keeps it afterwards.
 */
let counter = 0;

function freshId(type) {
  const prefix = clean(type).replace(/[^\w-]+/g, "-") || "object";

  const uuid =
    globalThis.crypto && typeof globalThis.crypto.randomUUID === "function"
      ? globalThis.crypto.randomUUID()
      : `${Date.now().toString(36)}-${(counter += 1)}-${Math.random().toString(16).slice(2, 8)}`;

  return `${prefix}-${uuid}`;
}

/*
 * The object's id, minted once and then kept.
 *
 * IT MUTATES THE OBJECT ONLY WHEN THERE IS NO ID, which is why a re-render, a
 * move, a feature change or a reopen can never produce a new identity.
 */
export function ensureObjectId(object, type = null) {
  if (!object || typeof object !== "object") {
    return null;
  }

  if (typeof object.id !== "string" || !object.id.trim()) {
    object.id = freshId(type || object.type || "object");
  }

  return object.id;
}

/* ============================================================
 * WRITING THE HEADER
 * ============================================================
 *
 * Options:
 *
 *   type       the internal type, when it differs from `object.type`
 *   label      what to call the object (defaults to its `name`)
 *   part       the logical object a primitive draws ("arrow", "label", ...)
 *   parent     the id of the object a component belongs to
 *   begin      write `DAETUM ID` (default true) - false for a component
 *   end        `true` to also close the block with `DAETUM END`
 *   version    the format version, when a caller wants it stated
 *
 * Returned as an ARRAY OF LINES so a caller joins them with the commands it
 * writes. Nothing here ends with a newline of its own.
 */
export function objectCommentHeader(object, options = {}) {
  const type = options.type || object?.type || "";
  const id = options.id || object?.id || null;

  const lines = [
    `% ${COMMENT_PREFIX} ${COMMENT_FIELDS.object}: ${objectDisplayName(object, {
      type,
      label: options.label,
    })}`,
  ];

  if (options.begin !== false && id) {
    lines.push(`% ${COMMENT_PREFIX} ${COMMENT_FIELDS.id}: ${clean(id)}`);
  }

  if (type) {
    lines.push(`% ${COMMENT_PREFIX} ${COMMENT_FIELDS.type}: ${clean(type)}`);
  }

  if (options.part) {
    lines.push(`% ${COMMENT_PREFIX} ${COMMENT_FIELDS.part}: ${clean(options.part)}`);
  }

  if (options.parent) {
    lines.push(`% ${COMMENT_PREFIX} ${COMMENT_FIELDS.parent}: ${clean(options.parent)}`);
  }

  if (Number.isFinite(Number(options.version)) && Number(options.version) > 0) {
    lines.push(`% ${COMMENT_PREFIX} VERSION: ${Number(options.version)}`);
  }

  return lines;
}

/* The closing marker of a block. */
export function objectCommentFooter(id) {
  return `% ${COMMENT_PREFIX} ${COMMENT_FIELDS.end}: ${clean(id)}`;
}

/*
 * THE SOURCE OF ONE OBJECT, WITH ITS HEADER.
 *
 * `commands` is what a writer produced. The result is the header directly
 * above the commands, and - only when asked - the closing marker. A writer
 * that produced nothing gets no header: a comment above no code would claim an
 * object the source does not draw.
 *
 * The header is directly above its code so that a header always labels the
 * commands beneath it, and every header is a block boundary - which is what
 * makes each object's region recoverable from the text.
 */
export function applyObjectComments(object, commands, options = {}) {
  const body = typeof commands === "string" ? commands.replace(/\s+$/, "") : "";

  if (!body.trim()) {
    return "";
  }

  const header = objectCommentHeader(object, options);
  const footer = options.end && object?.id ? [objectCommentFooter(options.id || object.id)] : [];

  return [...header, body, ...footer].join("\n");
}

/* ============================================================
 * COMPONENTS OF ONE LOGICAL OBJECT
 * ============================================================
 *
 * A force is an arrow, a label and a magnitude; a dimension is its witnesses,
 * its line, its arc and its text. They are ONE object to the student, and must
 * not become several selectable objects - but a component still needs an
 * identity when DAETUM has to talk about it (a warning about the label, a
 * future inline edit).
 *
 * The component's id is derived from its parent and its role, so it is stable
 * for as long as the object is: `force-1:label` is always the label of
 * `force-1`. It is NEVER a top-level id, so it can never be mistaken for an
 * object the model holds.
 */
export const PART_SEPARATOR = ":";

export function partId(parentId, part) {
  const parent = clean(parentId);
  const role = clean(part).replace(/\s+/g, "-").toLowerCase();

  return parent && role ? `${parent}${PART_SEPARATOR}${role}` : null;
}

/* Whether an id names a component rather than a top-level object. */
export function isPartId(id) {
  return String(id ?? "").includes(PART_SEPARATOR);
}

/* The object a component id belongs to, or null for a top-level id. */
export function parentIdOf(id) {
  const text = String(id ?? "");
  const at = text.lastIndexOf(PART_SEPARATOR);

  return at > 0 ? text.slice(0, at) : null;
}

